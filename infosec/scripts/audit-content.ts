// Generates docs/SOURCE_COVERAGE.md: per-slide/page coverage, bank statistics,
// cryptography checks against the Lab Manual, mock-exam totals and flagged source issues.
// Run: npm run audit:content
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { caesar, railEncrypt, routeEncrypt, vigenere } from "../src/crypto/ciphers";
import { formatSource, SOURCE_FILES, TOPICS, UNITS } from "../src/data/course";
import { FLASHCARDS } from "../src/data/flashcards";
import { LESSONS } from "../src/data/lessons";
import { QUESTIONS } from "../src/data/questions";
import { MISSING_INFO, SOURCE_NOTES } from "../src/data/sourceNotes";
import type { SourceFile } from "../src/data/types";
import { blueprintTotal, buildPaper, PAPERS } from "../src/exam/engine";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const lines: string[] = [];
const w = (s = "") => lines.push(s);

w("# Source coverage report — CSSY1208 Midterm Academy");
w();
w(`Generated by \`npm run audit:content\` on ${new Date().toISOString().slice(0, 10)}.`);
w();
w("Sources used (and nothing else): Lecture 1–4 slide decks and Lab Manual Part I. In-scope Lab Manual pages: **pg. 8–16 (Labs 4, 5, 6)**. Labs 1–3 (pg. 2–7) and Lab 7 (pg. 17–19) are excluded.");
w();

// ---------------------------------------------------------------- totals
w("## Content totals");
w();
w("| Item | Count |");
w("|---|---|");
w(`| Lessons | ${LESSONS.length} (${LESSONS.reduce((s, l) => s + l.blocks.length, 0)} blocks, every block with an Arabic explanation) |`);
w(`| Topics | ${TOPICS.length} |`);
w(`| Flashcards | ${FLASHCARDS.length} |`);
w(`| Questions | ${QUESTIONS.length} (${QUESTIONS.filter((q) => q.origin === "source").length} taken from the slides/manual, ${QUESTIONS.filter((q) => q.origin === "original").length} written from source facts) |`);
w();
const kinds = ["mcq", "tf", "fill", "match", "order", "short", "crypto"] as const;
w(`| Unit | ${kinds.join(" | ")} | total |`);
w(`|---|${kinds.map(() => "---").join("|")}|---|`);
for (const u of UNITS) {
  const qs = QUESTIONS.filter((q) => q.unitId === u.id);
  w(`| ${u.short} ${u.title} | ${kinds.map((k) => qs.filter((q) => q.kind === k).length).join(" | ")} | ${qs.length} |`);
}
w();
w(`Difficulty: ${(["easy", "medium", "hard"] as const).map((d) => `${d} ${QUESTIONS.filter((q) => q.difficulty === d).length}`).join(", ")}. Styles: ${["concept", "definition", "scenario", "procedure", "calculation", "alphabet"].map((s) => `${s} ${QUESTIONS.filter((q) => q.style === s).length}`).join(", ")}.`);
w();

// ---------------------------------------------------------------- coverage matrix
w("## Coverage by slide / page");
w();
w("L = lesson blocks citing it, Q = questions, F = flashcards. ⚠ = not taught (only title / textbook / thank-you slides should appear).");
w();
for (const file of Object.keys(SOURCE_FILES) as SourceFile[]) {
  const f = SOURCE_FILES[file];
  w(`### ${f.title}`);
  w();
  w(`| ${f.unitLabel} | L | Q | F | Lesson topics |`);
  w("|---|---|---|---|---|");
  for (const u of f.inScope) {
    const ls = LESSONS.filter((l) => l.blocks.some((b) => b.source.file === file && b.source.units.includes(u)));
    const L = LESSONS.reduce((s, l) => s + l.blocks.filter((b) => b.source.file === file && b.source.units.includes(u)).length, 0);
    const Q = QUESTIONS.filter((q) => q.sources.some((r) => r.file === file && r.units.includes(u))).length;
    const F = FLASHCARDS.filter((c) => c.source.file === file && c.source.units.includes(u)).length;
    w(`| ${u}${L === 0 ? " ⚠" : ""} | ${L} | ${Q} | ${F} | ${ls.map((l) => l.title).join("; ") || "—"} |`);
  }
  w();
}

// ---------------------------------------------------------------- crypto verification
w("## Cryptography: every Lab Manual example reproduced by the engine");
w();
const checks: [string, string, string][] = [
  ["Caesar SECRET, K=3 (pg. 14 solved example)", caesar("SECRET", 3, "encrypt").output, "VHFUHW"],
  ["Caesar CRYPTO, K=7 (pg. 14 question)", caesar("CRYPTO", 7, "encrypt").output, "JYFWAV"],
  ["Vigenère SECRET / WORD (pg. 15)", vigenere("SECRET", "WORD", "encrypt").output, "OSTUAH"],
  ["Rail Fence MUSCAT, depth 3 (pg. 15)", railEncrypt("MUSCAT", 3).output, "MAUCTS"],
  ["Rail Fence CIPHERTEXT, depth 3 (pg. 15–16)", railEncrypt("CIPHERTEXT", 3).output, "CEXIHRETPT"],
  ["Route HIDETHEGOLD 3×4, spiral clockwise from top-left (pg. 16 Ex. 1)", routeEncrypt("HIDETHEGOLD", 4, 3, "rows", "spiral-tl").output, "HIDHOXDLEETG"],
  ["Route Ex. 2, Key 1: top-right corner down to the left (pg. 16)", routeEncrypt("WEAREDISCOVEREDFLEEATONCE", 5, 5, "columns", "corner-tr").output, "TONCEADOEFLEEECRVERSADIEW"],
  ["Route Ex. 2, spiral model from top-right (pg. 16)", routeEncrypt("WEAREDISCOVEREDFLEEATONCE", 5, 5, "columns", "spiral-tr").output, "TONCEADOERAEWDVFLEEECSIER"],
];
w("| Example | Manual answer | Engine | Match |");
w("|---|---|---|---|");
let cryptoFail = 0;
for (const [name, got, want] of checks) {
  if (got !== want) cryptoFail++;
  w(`| ${name} | ${want} | ${got} | ${got === want ? "✅" : "❌"} |`);
}
w();

// ---------------------------------------------------------------- exam totals
w("## Mock exams");
w();
w(`Blueprint total: **${blueprintTotal()} marks** (practice setting — the official distribution was not provided).`);
w();
let bad = 0;
let n = 0;
for (const d of ["easy", "medium", "hard"] as const)
  for (let seed = 1; seed <= 300; seed++) {
    n++;
    const p = buildPaper(d, seed * 7919, "x");
    if (p.total !== 20) bad++;
  }
w(`Generated ${n} random papers (300 per difficulty): **${n - bad}/${n} total exactly 20 marks**.`);
w();
w("| Named paper | Total | Chapters / labs present |");
w("|---|---|---|");
for (const p of PAPERS) {
  const paper = buildPaper(p.difficulty, p.seed, p.title);
  const units = [...new Set(paper.items.map((i) => i.question.unitId))].sort();
  w(`| ${p.title} | ${paper.total} | ${units.join(", ")} |`);
}
w();

// ---------------------------------------------------------------- notes
w("## Missing or ambiguous source material");
w();
for (const s of SOURCE_NOTES) w(`- **${s.severity === "review" ? "Needs review" : "Info"} — ${formatSource(s.ref)}:** ${s.note} _Handling:_ ${s.handling}`);
w();
w("### Not specified in the course files");
w();
for (const m of MISSING_INFO) w(`- ${m}`);
w();

const out = resolve(root, "docs/SOURCE_COVERAGE.md");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join("\n") + "\n");
console.log(`Wrote ${out}`);
console.log(`Crypto examples: ${checks.length - cryptoFail}/${checks.length} match. Papers totalling 20: ${n - bad}/${n}.`);
if (cryptoFail || bad) process.exit(1);
